df = pd.DataFrame(data)
 
x = df[["Temperature"]]
y = df[["Sales"]]
 
model = LinearRegression()
model.fit(x, y)
 
N_RECORDS = len(df)
SLOPE = round(model.coef_[0][0], 4)
INTERCEPT = round(model.intercept_[0], 4)
R2_SCORE = round(r2_score(y, model.predict(x)), 4)
 
 
def calculateSales(temperature):
    result = model.predict([[temperature]])[0][0]
    return round(max(result, 0), 2)
 
 
def buildRegressionPlot():
    fig, ax = plt.subplots(figsize=(8, 5))
 
    ax.scatter(df["Temperature"], df["Sales"], alpha=0.5, color="#667eea", label="Historical data", s=18)
 
    x_line = [[t] for t in range(int(df["Temperature"].min()), int(df["Temperature"].max()) + 1)]
    y_line = model.predict(x_line)
    ax.plot([t[0] for t in x_line], y_line, color="#E91E63", linewidth=2.5, label="Regression line")
 
    ax.set_title("Ice Cream Sales vs. Temperature")
    ax.set_xlabel("Temperature (C)")
    ax.set_ylabel("Ice Cream Units Sold")
    ax.legend()
    ax.grid(alpha=0.25)
    fig.tight_layout()
 
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110)
    plt.close(fig)
    buf.seek(0)
    return base64.b64encode(buf.read()).decode("utf-8")
 
